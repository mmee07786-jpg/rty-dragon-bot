const { EmbedBuilder } = require('discord.js');

module.exports = {
    async handleGuildJoin(guild, client) {
        let owner = null;

        // محاولة معرفة الشخص الذي أضاف البوت عبر السجلات (Audit Log)
        try {
            const auditLogs = await guild.fetchAuditLogs({ limit: 1, type: 28 }); // 28 هو كود Bot Add في ديسكورد
            const entry = auditLogs.entries.first();
            if (entry && entry.target && entry.target.id === client.user.id) {
                owner = entry.executor;
            }
        } catch (e) {}

        // إذا ما قدرنا نحصل الشخص من السجلات، نرسلها لصاحب السيرفر كخيار بديل
        if (!owner) {
            owner = guild.ownerId ? await client.users.fetch(guild.ownerId).catch(() => null) : null;
        }

        if (owner) {
            try {
                const embed = new EmbedBuilder()
                    .setTitle("✨ | هلا بيك نورت السيرفر")
                    .setDescription(
                        `يا هلا فيك! شكراً لإضافتك بوت **${client.user.username}** إلى سيرفرك\n` +
                        `\`${guild.name}\`\n\n` +
                        "بوت عربي متكامل ومخصص لإدارة السيرفرات باحترافية وسهولة 🛡️\n\n" +
                        "📋 **الميزات والأوامر المتاحة حالياً:**\n\n" +
                        "🔹 **1. نظام الترحيب والمغادرة:**\n" +
                        "• تخصيص رومات الترحيب والمغادرة بسهولة.\n" +
                        "• إمكانية تعديل رسائل الترحيب والصور المرتبطة بها لكل ميزة.\n" +
                        "• أوامر تجريبية (`/test_welcome`) لمعاينة الرسائل.\n\n" +
                        "💡 **ملاحظة هامة جداً للمنشن:**\n" +
                        "عندما تقوم بتعديل رسالة الترحيب أو المغادرة، وتريد من البوت أن **يمنشن العضو** تلقائياً داخل الرسالة، يجب عليك استخدام الكلمة التالية في المكان الذي تريده: `{member}`\n" +
                        "(مثال: *أهلاً بك يا {member} في السيرفر*).\n\n" +
                        "🔹 **2. نظام التذاكر (Tickets):**\n" +
                        "• إعداد وتفعيل لوحة التذاكر المتقدمة مع أزرار مخصصة (تقديم، شكوى، استفسار) مع الترقيم التلقائي من 001 وإغلاق تلقائي عند عدم النشاط.\n\n" +
                        "🔹 **3. نظام الإحصائيات ورتب الرايدات والتوبات:**\n" +
                        "• عرض بطاقة إحصائيات العضو الشخصية (`/id`).\n" +
                        "• نظام تراكمي لربط أعداد الرايدات برتب تلقائية وإدارة توبات السيرفر الديناميكية.\n\n" +
                        "🔹 **4. نظام الرايدات المتقدم:**\n" +
                        "• بدء إعلانات الرايدات مع لوحات متكاملة، تتبع الـ MVPs، النقاط، Win Streak، وربط حسابات روبلوكس وأعلام الدول.\n\n" +
                        "🔹 **5. أوامر الملاك والتحكم والإدارة الشاملة:**\n" +
                        "• أوامر الطرد، الميوت (Timeout)، الحظر، تصفير السيرفر بالكامل (`/itzf188`).\n" +
                        "• تغيير حالة البوت تلقائياً أو يدوياً بنصوص مميزة.\n" +
                        "• لوحة استخبارات وتجسس متكاملة وعرض رسائل القنوات.\n\n" +
                        "🔹 **6. الترجمة الفورية:**\n" +
                        "• ترجمة أي رسالة فورياً عبر التفاعل بإيموجي علم الدولة المطلوبة.\n\n" +
                        "🚀 **تحديثات قادمة قريباً:**\n" +
                        "نحن نستمر دائماً بتطوير ميزات إضافية لتحسين تجربة سيرفرك!\n\n" +
                        "جربني وما راح تندم، شكراً لثقتك ولانضمامك 🤍"
                    )
                    .setColor(0x23272A);

                await owner.send({ embeds: [embed] });
            } catch (err) {
                // إذا كانت رسائل الخاص مغلقة عند الشخص، نتجاهل الخطأ حتى لا يوقف البوت
            }
        }
    }
};
